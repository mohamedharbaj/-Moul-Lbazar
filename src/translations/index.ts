// City labels are stored as "عربي (Latin)". Arabic UI shows the full label,
// French/English UI show only the Latin part.
const CITY_EN_OVERRIDES: Record<string, string> = {
  'خارج المغرب (International / MRE)': 'Outside Morocco (International / MRE)',
  'مدينة أخرى (Autre ville)': 'Other city',
};
export const getCityLabel = (city: string, lang: Language): string => {
  if (lang === 'ar') return city;
  if (lang === 'en' && CITY_EN_OVERRIDES[city]) return CITY_EN_OVERRIDES[city];
  const m = city.match(/\(([^)]+)\)/);
  return m ? m[1] : city;
};

